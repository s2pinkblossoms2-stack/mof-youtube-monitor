// 개인정보 걸러내기 (PRD 7장): 전화번호·이메일·주민등록번호 형태가 있으면 "개인정보 포함"으로 본다.
// 이런 댓글은 AI에 보내지 않는다. 놓치는 것보다 잘못 거르는 쪽이 안전해서 넓게 잡는다.

const PATTERNS: RegExp[] = [
  // 전화번호: 010-1234-5678, 02-123-4567, 01012345678, 010 1234 5678
  /(?<!\d)0\d{1,2}[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)/,
  // 이메일
  /[A-Za-z0-9._%+-]+\s?@\s?[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+/,
  // 주민등록번호: 900101-1234567
  /(?<!\d)\d{6}\s?-?\s?[1-4]\d{6}(?!\d)/,
];

export function hasPersonalInfo(text: string): boolean {
  return PATTERNS.some((p) => p.test(text));
}
